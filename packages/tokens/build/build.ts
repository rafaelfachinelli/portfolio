// Builds dist/tokens.css (CSS variables), dist/theme.css (Tailwind 4 theme)
// and dist/tokens.json from the DTCG sources in src/tokens.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { cssVar } from '../src/index'
import { type FlatToken, resolver, resolveTokens, seasonContexts } from '../src/resolve'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'dist')

function cssValue(token: FlatToken): string {
  const { type, value } = token
  if (type === 'dimension' && value && typeof value === 'object') {
    const v = value as { value: number; unit: string }
    return `${v.value}${v.unit}`
  }
  if (type === 'fontFamily' && Array.isArray(value)) {
    return value.map(f => (/[\s']/.test(f) ? `"${f}"` : f)).join(', ')
  }
  return String(value)
}

function declarations(tokens: FlatToken[]): string {
  return tokens.map(t => `  ${cssVar(t.path)}: ${cssValue(t)};`).join('\n')
}

const base = resolveTokens(resolver.modifiers.season.default)
const seasonTokens = (season: string) =>
  resolveTokens(season).filter(t => t.path.startsWith('season.'))

const header = '/* Generated by @datum/tokens (build/build.ts). Do not edit by hand. */\n'

// 1. CSS variables: base theme on :root, each season on [data-season].
const seasonBlocks = seasonContexts
  .filter(id => id !== resolver.modifiers.season.default)
  .map(id => `[data-season='${id}'] {\n${declarations(seasonTokens(id))}\n}`)
  .join('\n\n')

const tokensCss = `${header}
:root {
${declarations(base)}
  color-scheme: dark;
}

${seasonBlocks}
`

// 2. Tailwind 4 theme: utilities that point at the variables (bg-board, text-ink,
// border-line, text-season-accent, font-display, rounded-datum...).
const colorUtilities = base
  .filter(t => t.type === 'color' && (t.path.startsWith('color.') || t.path.startsWith('season.')))
  .map(t => {
    const name = t.path.startsWith('season.') ? t.path.replace('.', '-') : t.path.replace('color.', '')
    return `  --color-${name}: var(${cssVar(t.path)});`
  })
  .join('\n')

const themeCss = `${header}
@theme inline {
${colorUtilities}
  --font-display: var(${cssVar('font.display')});
  --radius-datum: var(${cssVar('radius.sm')});
}
`

// 3. JSON for docs and tools (Storybook swatches, tests).
const json = {
  base: Object.fromEntries(base.map(t => [t.path, { type: t.type, value: t.value, description: t.description }])),
  seasons: Object.fromEntries(
    seasonContexts.map(id => [id, Object.fromEntries(seasonTokens(id).map(t => [t.path, t.value]))]),
  ),
}

fs.mkdirSync(dist, { recursive: true })
fs.writeFileSync(path.join(dist, 'tokens.css'), tokensCss)
fs.writeFileSync(path.join(dist, 'theme.css'), themeCss)
fs.writeFileSync(path.join(dist, 'tokens.json'), `${JSON.stringify(json, null, 2)}\n`)

console.log(`@datum/tokens: ${base.length} base tokens, ${seasonContexts.length} seasons -> dist/`)
